package generator

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path/filepath"
	"slices"
	"strings"

	"github.com/451008604/deepcopy-gen/types"
)

const helperImport = "github.com/451008604/deepcopy-gen/deepcopy"

// GeneratedHeader identifies files written by deepcopy-gen.
const GeneratedHeader = "// Code generated by github.com/451008604/deepcopy-gen. DO NOT EDIT."

type Options struct{}

func Generate(pkg types.PackageInfo) (string, error) {
	return GenerateWithOptions(pkg, Options{})
}

func GenerateWithOptions(pkg types.PackageInfo, opts Options) (string, error) {
	g := &genState{
		pkgName:       pkg.Name,
		imports:       make(map[string]bool),
		identifiers:   make(map[string]bool),
		names:         make(map[string]string),
		typeExprCache: make(map[string]string),
	}

	for _, name := range pkg.Identifiers {
		g.identifiers[name] = true
	}
	for _, item := range pkg.Structs {
		g.identifiers[item.Name] = true
		for _, name := range item.TypeParams {
			g.identifiers[name] = true
		}
	}
	g.helperAlias = g.localName("dc")
	g.visited = g.localName("v")
	methods := make([]string, 0, len(pkg.Structs))
	for _, s := range pkg.Structs {
		methods = append(methods, g.genDeepCopy(s))
	}

	code, err := format.Source([]byte(g.assemble(methods)))
	if err != nil {
		return "", fmt.Errorf("format generated package %s: %w", pkg.Name, err)
	}
	return string(code), nil
}

func ValidateGenerated(code string) error {
	fset := token.NewFileSet()
	_, err := parser.ParseFile(fset, "deepcopy.dc.go", code, parser.AllErrors)
	return err
}

func OutputPath(pkgDir string) string {
	return filepath.Join(pkgDir, "deepcopy.dc.go")
}

type genState struct {
	pkgName       string
	imports       map[string]bool
	needsHelper   bool
	importAliases map[string]string
	depth         int
	identifiers   map[string]bool
	names         map[string]string
	helperAlias   string
	visited       string
	typeExprCache map[string]string
}

func (g *genState) assemble(methods []string) string {
	var b strings.Builder
	size := 128
	for _, method := range methods {
		size += len(method) + 1
	}
	b.Grow(size)

	b.WriteString(GeneratedHeader + "\n\n")
	b.WriteString(fmt.Sprintf("package %s\n", g.pkgName))

	if g.needsHelper {
		g.imports[helperImport] = true
	}

	if len(g.imports) > 0 {
		b.WriteString("\nimport (\n")
		paths := make([]string, 0, len(g.imports))
		for p := range g.imports {
			paths = append(paths, p)
		}
		slices.Sort(paths)
		for _, p := range paths {
			if p == helperImport {
				alias := g.helperAlias
				if alias == "" {
					alias = "dc"
				}
				fmt.Fprintf(&b, "\t%s %q\n", alias, helperImport)
			} else if alias := g.importAliases[p]; alias != "" {
				b.WriteString(fmt.Sprintf("\t%s %q\n", alias, p))
			} else {
				b.WriteString(fmt.Sprintf("\t%q\n", p))
			}
		}
		b.WriteString(")\n")
	}

	for _, m := range methods {
		b.WriteString("\n")
		b.WriteString(m)
	}

	return b.String()
}

// 为同包和跨包调用共享访问记录，避免递归容器重新开始复制。
func (g *genState) genDeepCopy(s types.StructInfo) string {
	g.needsHelper = true
	name := s.Name
	if len(s.TypeParams) > 0 {
		name += "[" + strings.Join(s.TypeParams, ", ") + "]"
	}
	in, out, ok := g.localName("in"), g.localName("out"), g.localName("ok")
	visited, helper := g.visited, g.helperAlias
	valueOnly := true
	if s.Underlying != nil {
		valueOnly = !needsDeepCopy(*s.Underlying)
	} else {
		for _, field := range s.Fields {
			if needsDeepCopy(field) {
				valueOnly = false
				break
			}
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// DeepCopy returns a deep copy of %s.\n", s.Name)
	fmt.Fprintf(&b, "func (%s *%s) DeepCopy() *%s {\n", in, name, name)
	if valueOnly {
		// 独立复制纯值对象无需访问记录；共享调用仍走下方的跟踪入口。
		fmt.Fprintf(&b, "if %s == nil { return nil }; %s := new(%s); *%s = *%s; return %s\n", in, out, name, out, in, out)
	} else {
		fmt.Fprintf(&b, "return %s.deepcopy(make(%s.Visited))\n", in, helper)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// DeepCopyWithVisited shares pointer tracking across generated packages.\nfunc (%s *%s) DeepCopyWithVisited(%s %s.Visited) *%s {\nif %s == nil { %s = make(%s.Visited) }; return %s.deepcopy(%s)\n}\n\n", in, name, visited, helper, name, visited, visited, helper, in, visited)
	fmt.Fprintf(&b, "func (%s *%s) deepcopy(%s %s.Visited) *%s {\n", in, name, visited, helper, name)
	fmt.Fprintf(&b, "if %s == nil { return nil }\n", in)
	fmt.Fprintf(&b, "if %s, %s := %s[%s]; %s { return %s.(*%s) }\n", out, ok, visited, in, ok, out, name)
	fmt.Fprintf(&b, "%s := new(%s)\n%s[%s] = %s\n*%s = *%s\n", out, name, visited, in, out, out, in)
	if s.Underlying != nil {
		u := *s.Underlying
		u.TypeExpr = name
		b.WriteString(g.genFieldCopyVisited("(*"+out+")", "(*"+in+")", u))
	} else {
		for _, field := range s.Fields {
			if needsDeepCopy(field) {
				b.WriteString(g.genFieldCopyVisited(out+"."+field.Name, in+"."+field.Name, field))
			}
		}
	}
	fmt.Fprintf(&b, "return %s\n}\n", out)
	return b.String()
}

// 同一生成单元内稳定分配名称，避让包声明、导入和类型参数。
func (g *genState) localName(base string) string {
	if name := g.names[base]; name != "" {
		return name
	}
	name := base
	for index := 1; g.identifiers[name]; index++ {
		name = fmt.Sprintf("%s%d", base, index)
	}
	g.names[base] = name
	g.identifiers[name] = true
	return name
}

func needsDeepCopy(f types.FieldInfo) bool {
	switch f.Category {
	case types.TypePointer, types.TypeSlice, types.TypeMap, types.TypeParameter:
		return true
	case types.TypeArray:
		return f.ElemType != nil && needsDeepCopy(*f.ElemType)
	case types.TypeStruct:
		if f.PackageName != "" || f.HasDeepCopy {
			return true
		}
		for _, field := range f.AnonFields {
			if needsDeepCopy(field) {
				return true
			}
		}
	}
	return false
}

func isBuiltinValue(f types.FieldInfo) bool {
	return f.Category == types.TypeBasic && f.TypeName == ""
}

// 仅对形状明确的叶子使用快捷函数，其余组合递归生成。
func (g *genState) genFieldCopyVisited(dst, src string, f types.FieldInfo) string {
	switch f.Category {
	case types.TypeParameter:
		return fmt.Sprintf("%s = %s.CopyValue(%s, %s)\n", dst, g.helperAlias, g.visited, src)
	case types.TypeStruct:
		if f.HasDeepCopy {
			return fmt.Sprintf("%s = *%s.deepcopy(%s)\n", dst, src, g.visited)
		}
		if f.PackageName != "" {
			return fmt.Sprintf("%s = *%s.CopyPtr(%s, &%s)\n", dst, g.helperAlias, g.visited, src)
		}
		var b strings.Builder
		fmt.Fprintf(&b, "%s = %s\n", dst, src)
		for _, field := range f.AnonFields {
			if needsDeepCopy(field) {
				b.WriteString(g.genFieldCopyVisited(dst+"."+field.Name, src+"."+field.Name, field))
			}
		}
		return b.String()
	case types.TypePointer:
		elem := *f.ElemType
		if elem.HasDeepCopy {
			if !strings.HasPrefix(f.TypeExpr, "*") {
				src = "(*" + g.typeExpr(elem) + ")(" + src + ")"
			}
			return fmt.Sprintf("%s = %s.deepcopy(%s)\n", dst, src, g.visited)
		}
		if !needsDeepCopy(elem) || elem.PackageName != "" {
			return fmt.Sprintf("%s = %s.CopyPtr(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		if elem.Category == types.TypePointer && !needsDeepCopy(*elem.ElemType) {
			return fmt.Sprintf("%s = %s.CopyDoublePtr(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		var b strings.Builder
		cached, ok := g.localName("cached"), g.localName("ok")
		fmt.Fprintf(&b, "if %s != nil {\nif %s, %s := %s[%s]; %s {\n%s = %s.(%s)\n} else {\n", src, cached, ok, g.visited, src, ok, dst, cached, g.typeExpr(f))
		fmt.Fprintf(&b, "%s = new(%s)\n%s[%s] = %s\n*%s = *%s\n", dst, g.typeExpr(elem), g.visited, src, dst, dst, src)
		b.WriteString(g.genFieldCopyVisited("(*"+dst+")", "(*"+src+")", elem))
		b.WriteString("}\n} else {\n" + dst + " = nil\n}\n")
		return b.String()
	case types.TypeSlice:
		elem := *f.ElemType
		if !needsDeepCopy(elem) {
			return fmt.Sprintf("%s = %s.CopySlice(%s)\n", dst, g.helperAlias, src)
		}
		if elem.Category == types.TypePointer && strings.HasPrefix(elem.TypeExpr, "*") && (!needsDeepCopy(*elem.ElemType) || elem.ElemType.HasDeepCopy || elem.ElemType.PackageName != "") {
			return fmt.Sprintf("%s = %s.CopySlicePtr(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		if elem.Category == types.TypeSlice && !needsDeepCopy(*elem.ElemType) && !isBuiltinValue(*elem.ElemType) {
			return fmt.Sprintf("%s = %s.CopySliceSlice(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		if elem.Category == types.TypeMap && !needsDeepCopy(*elem.MapValueType) && !isBuiltinValue(*elem.MapValueType) {
			return fmt.Sprintf("%s = %s.CopySliceMap[%s, %s](%s, %s)\n", dst, g.helperAlias, g.typeExpr(*elem.MapKeyType), g.typeExpr(*elem.MapValueType), g.visited, src)
		}
		fallthrough
	case types.TypeArray:
		if !needsDeepCopy(*f.ElemType) {
			return ""
		}
		var b strings.Builder
		if f.Category == types.TypeSlice {
			fmt.Fprintf(&b, "if %s != nil {\n%s = make(%s, len(%s))\n", src, dst, g.typeExpr(f), src)
		}
		index := "i"
		if g.depth > 0 {
			index = fmt.Sprintf("i%d", g.depth)
		}
		index = g.localName(index)
		g.depth++
		fmt.Fprintf(&b, "for %s := range %s {\n%s[%s] = %s[%s]\n", index, src, dst, index, src, index)
		b.WriteString(g.genFieldCopyVisited(dst+"["+index+"]", src+"["+index+"]", *f.ElemType))
		g.depth--
		b.WriteString("}\n")
		if f.Category == types.TypeSlice {
			fmt.Fprintf(&b, "} else { %s = nil }\n", dst)
		}
		return b.String()
	case types.TypeMap:
		value := *f.MapValueType
		if isBuiltinValue(value) {
			if g.importAliases == nil {
				g.importAliases = make(map[string]string)
			}
			if g.importAliases["maps"] == "" {
				g.importAliases["maps"] = g.localName("maps")
			}
			g.imports["maps"] = true
			return fmt.Sprintf("%s = %s.Clone(%s)\n", dst, g.importAliases["maps"], src)
		}
		if !needsDeepCopy(value) && value.Category != types.TypeStruct {
			return fmt.Sprintf("%s = %s.CopyMap(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		if value.Category == types.TypePointer && strings.HasPrefix(value.TypeExpr, "*") && (!needsDeepCopy(*value.ElemType) || value.ElemType.HasDeepCopy || value.ElemType.PackageName != "") {
			return fmt.Sprintf("%s = %s.CopyMapPtr(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		if value.Category == types.TypeSlice && !needsDeepCopy(*value.ElemType) && !isBuiltinValue(*value.ElemType) {
			return fmt.Sprintf("%s = %s.CopyMapSlice(%s, %s)\n", dst, g.helperAlias, g.visited, src)
		}
		var b strings.Builder
		key, val, cp := "k", "val", "cp"
		if g.depth > 0 {
			key += fmt.Sprint(g.depth)
			val += fmt.Sprint(g.depth)
			cp += fmt.Sprint(g.depth)
		}
		key, val, cp = g.localName(key), g.localName(val), g.localName(cp)
		g.depth++
		fmt.Fprintf(&b, "if %s != nil {\n%s = make(%s, len(%s))\nfor %s, %s := range %s {\n", src, dst, g.typeExpr(f), src, key, val, src)
		if value.HasDeepCopy || value.PackageName != "" {
			// Go 1.21 的 range 变量复用地址，必须创建本轮独立值。
			fmt.Fprintf(&b, "%s := %s\n", val, val)
			b.WriteString(g.genFieldCopyVisited(dst+"["+key+"]", val, value))
		} else if needsDeepCopy(value) {
			fmt.Fprintf(&b, "%s := %s\n", cp, val)
			b.WriteString(g.genFieldCopyVisited(cp, val, value))
			fmt.Fprintf(&b, "%s[%s] = %s\n", dst, key, cp)
		} else {
			fmt.Fprintf(&b, "%s[%s] = %s\n", dst, key, val)
		}
		g.depth--
		fmt.Fprintf(&b, "}\n} else { %s = nil }\n", dst)
		return b.String()
	}
	return ""
}

// 只记录实际出现在生成类型表达式中的导入，保留别名及嵌套类型依赖。
func (g *genState) typeExpr(f types.FieldInfo) string {
	if expr, ok := g.typeExprCache[f.TypeExpr]; ok {
		return expr
	}
	expr, err := parser.ParseExpr(f.TypeExpr)
	if err == nil {
		ast.Inspect(expr, func(node ast.Node) bool {
			if sel, ok := node.(*ast.SelectorExpr); ok {
				if ident, ok := sel.X.(*ast.Ident); ok {
					if path := f.Imports[ident.Name]; path != "" {
						g.imports[path] = true
						if path == helperImport {
							ident.Name = g.helperAlias
						} else if alias := g.importAliases[path]; alias != "" {
							ident.Name = alias
						}
						if g.importAliases == nil {
							g.importAliases = make(map[string]string)
						}
						g.importAliases[path] = ident.Name
					}
				}
			}
			return true
		})
		var b bytes.Buffer
		if err := format.Node(&b, token.NewFileSet(), expr); err == nil {
			result := b.String()
			if g.typeExprCache != nil {
				g.typeExprCache[f.TypeExpr] = result
			}
			return result
		}
	}
	return f.TypeExpr
}
